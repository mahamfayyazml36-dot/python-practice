# What it does: Takes name, age, city, and favorite subject from user
# and prints a simple introduction.
name = input("What is your name?")
age = input("How old are you?")
city = input("Which city do you live in?")
subject = input("What is your favorite subject?")

print("\n----Student introduction----")
print("Name:", name)
print("Age:", age)
print("City:", city)
print("Favorite Subject:", subject)

print("\nHello", name + "!")
print("You are",age, "years old and you live in",city + ".")
print("Your favorite subject is", subject + ".")
